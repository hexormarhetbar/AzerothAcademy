#!/bin/sh
# Azeroth Academy - convert posed portrait PNGs into WoW-ready TGA files.
#
# Usage:  sh tools/convert_art.sh [source_dir]      (default source: Media/Art/src)
#
# PNGs to put in the source folder (any size, transparent background, full figure):
#   fizzwick_<pose>.png  for poses: greet talking thinking researching teaching excited
#                        celebrating proud encouraging tinkering surprised
#   sprocket_squawk.png  sprocket_curious.png
#   fizzwick_strip.png   (optional talk animation: 2, 4 or 8 frames side by side)
#   zixi_portrait.png  quill_portrait.png   (host portraits: Chronicler Zixi, Archivist Quill.
#                        The Murloc Tidehunter has no slot: it stays on the in-game model.)
# Output, in Media/Art/:
#   <name>.tga       512x512 32-bit uncompressed TGA, alpha kept, bottom-left origin
#   <name>_head.tga  256x256 head-and-chest crop for small portrait slots. Made with
#                    tools/make_heads.py (face-centered; needs python3 + Pillow + numpy).
#                    Without Python, a <name>_head.png you supply is used, else a plain
#                    top-center crop.
# Existing TGAs without a matching PNG are kept (only PNGs you supply are converted).
# Media/Art/Manifest.lua is rewritten to list exactly the files present, so the addon
# only asks for art that exists. Needs ImageMagick 7 ("magick") or 6 ("convert").
# Reload the UI (/reload) afterwards; brand-new files need a full game restart.
set -e
cd "$(dirname "$0")/.."
SRC="${1:-Media/Art/src}"
OUT="Media/Art"
POSES="greet talking thinking researching teaching excited celebrating proud encouraging tinkering surprised"
NAMES=""
for p in $POSES; do NAMES="$NAMES fizzwick_$p"; done
NAMES="$NAMES sprocket_squawk sprocket_curious"
for h in zixi quill; do NAMES="$NAMES ${h}_portrait"; done

if command -v magick >/dev/null 2>&1; then IM="magick"
elif command -v convert >/dev/null 2>&1; then IM="convert"
else
  echo "ImageMagick not found. Install it (e.g. 'sudo apt install imagemagick' or 'brew install imagemagick')." >&2
  exit 1
fi
if [ ! -d "$SRC" ]; then echo "Source folder not found: $SRC" >&2; exit 1; fi
FRAMES="${STRIP_FRAMES:-4}"
case "$FRAMES" in 2|4|8) ;; *) echo "STRIP_FRAMES must be 2, 4 or 8" >&2; exit 1 ;; esac
mkdir -p "$OUT"

# WoW reads TGA rows bottom-up: flip and store with a bottom-left origin (descriptor 0x08).
tga() { $IM "$@" -alpha on -depth 8 -compress None -flip -orient BottomLeft "$TGA_OUT"; }
square() { TGA_OUT="$3"; tga "$1" -resize "$2x$2" -background none -gravity center -extent "$2x$2"; }

HEADS_PY=0
if command -v python3 >/dev/null 2>&1 && python3 -c "import PIL, numpy" >/dev/null 2>&1; then HEADS_PY=1; fi

for name in $NAMES; do
  if [ -f "$SRC/$name.png" ]; then
    square "$SRC/$name.png" 512 "$OUT/$name.tga"
    echo "converted $name"
    if [ "$HEADS_PY" = 0 ]; then
      if [ -f "$SRC/${name}_head.png" ]; then
        square "$SRC/${name}_head.png" 256 "$OUT/${name}_head.tga"
      else
        TGA_OUT="$OUT/${name}_head.tga"
        tga "$SRC/$name.png" -resize 512x512 -background none -gravity center -extent 512x512 \
          -gravity north -crop 256x256+0+0 +repage
      fi
      echo "  head crop (simple) ${name}_head"
    fi
  fi
  # No PNG for this name: keep any TGA already in Media/Art (since v1.0, so adding host
  # portraits never wipes the shipped Fizzwick poses). Delete a TGA by hand to remove it.
done
if [ "$HEADS_PY" = 1 ]; then
  python3 tools/make_heads.py "$SRC" "$OUT"
fi
if [ -f "$SRC/fizzwick_strip.png" ]; then
  W=$((FRAMES * 256))
  TGA_OUT="$OUT/fizzwick_strip.tga"
  tga "$SRC/fizzwick_strip.png" -resize "${W}x256!" -background none
  echo "converted fizzwick_strip ($FRAMES frames, ${W}x256)"
fi

{
  echo "-- Generated by tools/convert_art.sh. Lists the custom portraits present in Media/Art."
  echo "-- Empty = no custom art: Fizzwick uses the in-game goblin model (then an icon)."
  echo "-- Hosts without a <host>_portrait file show their runtime placeholder."
  echo "local _, ns = ..."
  echo "ns.ArtManifest = {"
  for name in $NAMES; do
    [ -f "$OUT/$name.tga" ] && echo "  $name = true,"
    [ -f "$OUT/${name}_head.tga" ] && echo "  ${name}_head = true,"
  done
  [ -f "$OUT/fizzwick_strip.tga" ] && echo "  fizzwick_strip = { frames = $FRAMES },"
  echo "}"
} > "$OUT/Manifest.lua"
echo "wrote $OUT/Manifest.lua"
