#!/usr/bin/env python3
"""Write Core/TonguesClips.lua from tools/tongues_clips.tsv (dev tool, v1.2).

The TSV lists every shipped World Tongues clip: file name (Media/Sounds/Tongues/<clip>.ogg),
course, the native text exactly as it appears in Core/TonguesData.lua, and the length in
seconds of the mastered file. Re-run after adding or re-mastering clips:

    python3 tools/gen_tongues_clips.py            # rewrite the Lua table
    python3 tools/gen_tongues_clips.py --durations  # also re-measure seconds with ffprobe
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "tools", "tongues_clips.tsv")
OUT = os.path.join(ROOT, "Core", "TonguesClips.lua")
SND = os.path.join(ROOT, "Media", "Sounds", "Tongues")

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main():
    remeasure = "--durations" in sys.argv
    rows = []
    for line in open(TSV, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        clip, lang, native, dur = line.rstrip("\n").split("\t")
        path = os.path.join(SND, clip + ".ogg")
        if not os.path.exists(path):
            sys.exit("missing clip file: " + path)
        if remeasure:
            dur = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                                 capture_output=True, text=True, check=True).stdout.strip()
        rows.append((clip, lang, native, round(float(dur), 2)))
    out = ["-- GENERATED by tools/gen_tongues_clips.py from tools/tongues_clips.tsv. Do not edit by hand.",
           "-- World Tongues voice clips (v1.2): course -> native text -> { file, seconds }.",
           "-- Voices generated with ElevenLabs (original designed voices, no cloning); see Media/Sounds/Tongues/README.md.",
           "local _, ns = ...", "ns.TonguesClipData = {"]
    for lang in ("ja", "es"):
        out.append("  %s = {" % lang)
        for clip, l, native, dur in rows:
            if l == lang:
                out.append("    [%s] = { %s, %s }," % (lua_str(native), lua_str(clip), repr(dur)))
        out.append("  },")
    out.append("}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    if remeasure:
        with open(TSV, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("# clip\tlang\tnative text (exactly as in Core/TonguesData.lua)\tseconds\n")
            for r in rows: fh.write("%s\t%s\t%s\t%s\n" % r)
    print("%d clips -> %s" % (len(rows), os.path.relpath(OUT, ROOT)))

if __name__ == "__main__":
    main()
